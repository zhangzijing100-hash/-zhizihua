/** 某个盘在游戏里的序号；查不到返回 Infinity（排到该轮末尾） */
export function wheelOrderOf(gameEntryId) {
  const v = WHEEL_ENTRY_ORDER[gameEntryId];
  return v === undefined ? Number.POSITIVE_INFINITY : v;
}

/** 某个轮在游戏里的序号；查不到返回 Infinity */
export function categoryOrderOf(categoryId) {
  const i = WHEEL_CATEGORY_ORDER.indexOf(categoryId);
  return i < 0 ? Number.POSITIVE_INFINITY : i;
}
